#!/usr/bin/env python3
"""Prepare the released FLARE-LLM Large sources; opt in to ~25 GB downloads."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
FLARE_REV = '7c8f76c788a01f9270a3badfd2eeab45a979c44a'
CHECKPOINT_REV = '6187ad650dc1786a8efc8b6bfbee37bbf62c4b2e'
QWEN_REV = 'd149729398750b98c0af14eb82c78cfe92750796'
CHECKPOINTS = [
    'exp_22_2_large/checkpoints/checkpoint_52_800000.pt',
    'exp_22_2_large/finetuned/checkpoints/checkpoint_last.pt',
    'lipreading_exp_2_large_face_lip_s2/checkpoints/checkpoint_4_60000.pt',
]
MEAN_FACE_URL = 'https://huggingface.co/nguyenvulebinh/AV-HuBERT/resolve/1484d31729f9081903cf97fa0429387fa575b16f/20words_mean_face.npy'
MEAN_FACE_SHA = 'dbf68b2044171e1160716df7c53e8bbfaa0ee8c61fb41171d04cb6092bb81422'


def prepare_sources():
    vendor = ROOT / 'vendor' / 'FLARE'
    if not vendor.exists():
        subprocess.run(['git', 'clone', 'https://github.com/jxzhanggg/FLARE.git', str(vendor)], check=True)
        subprocess.run(['git', '-C', str(vendor), 'checkout', '--detach', FLARE_REV], check=True)
    actual = subprocess.check_output(['git', '-C', str(vendor), 'rev-parse', 'HEAD'], text=True).strip()
    if actual != FLARE_REV:
        raise SystemExit(f'Expected upstream {FLARE_REV}; found {actual}. Use a clean pinned checkout.')
    # Generate a separate importable runtime copy, preserving upstream unchanged.
    # Only inference classes are used, so dataset/task registration is unnecessary.
    runtime = ROOT / 'vendor' / 'flare_runtime'
    import shutil
    shutil.copytree(vendor / 'flare_llm', runtime, dirs_exist_ok=True)
    (runtime / '__init__.py').write_text('# Inference-only package generated by scripts/setup_model.py\n')
    for relative in ['models/hubert_asr_chime_s3_llm.py', 'models/hubert_distill_frm_whisper_offline_bestrq_dual_frontend.py']:
        p = runtime / relative
        s = p.read_text()
        s = 'from typing import Any\nAVHubertPretrainingConfig = Any\nAVHubertPretrainingTask = Any\n' + s
        s = s.replace('DBG=True if len(sys.argv) == 1 else False', 'DBG=False')
        # Annotation-only task types otherwise pull in training-only dataset dependencies.
        s = re.sub(r'    from (?:\.\.)?hubert_pretraining import \(\s*AVHubertPretrainingConfig,\s*AVHubertPretrainingTask,\s*\)', '', s)
        if relative.endswith('hubert_asr_chime_s3_llm.py'):
            s = s.replace('import sys,logging', 'import sys,logging,os')
            s = s.replace('model_name_or_path = "pretrain_models/QW2.5"', 'model_name_or_path = os.environ["FLARE_QWEN_PATH"]')
            s = s.replace('trust_remote_code=True', 'trust_remote_code=False, local_files_only=True')
            s = s.replace('torch_dtype=torch.bfloat16)', 'torch_dtype=torch.bfloat16, local_files_only=True)')
        else:
            s = s.replace("stat_path = '/work2/asrprg/anonymous/lippretrain/extract_whisper_fea/whisper_last1.stat.npy'", 'stat_path = os.environ["FLARE_WHISPER_STAT"]')
        p.write_text(s)
    (runtime / 'SOURCE.json').write_text(json.dumps({'repository': 'https://github.com/jxzhanggg/FLARE', 'revision': FLARE_REV, 'patches': ['inference-only imports', 'deterministic package imports', 'local Qwen path', 'Whisper statistics recovered from checkpoint']}, indent=2))
    print(f'Prepared inference sources at {runtime}', flush=True)


def download_assets():
    from huggingface_hub import hf_hub_download, snapshot_download
    assets = ROOT / 'models'
    assets.mkdir(exist_ok=True)
    repo = 'Anony94/FLARE-checkpoints'
    revision = CHECKPOINT_REV
    for filename in CHECKPOINTS:
        print(f'Downloading {filename}', flush=True)
        hf_hub_download(repo, filename, revision=revision, local_dir=assets / 'FLARE-checkpoints')
    qwen_revision = QWEN_REV
    snapshot_download('Qwen/Qwen2.5-7B', revision=qwen_revision, local_dir=assets / 'Qwen2.5-7B', allow_patterns=['*.json', '*.safetensors', 'merges.txt', 'vocab.json', '*.tiktoken'])
    mean = urllib.request.urlopen(MEAN_FACE_URL, timeout=60).read()
    if hashlib.sha256(mean).hexdigest() != MEAN_FACE_SHA:
        raise RuntimeError('Mean-face checksum mismatch')
    (assets / '20words_mean_face.npy').write_bytes(mean)
    # Mirrors contain the exact files named by upstream; verify their full SHA256.
    import torch
    landmark_files = {
        's3fd-619a316812.pth': '619a31681264d3f7f7fc7a16a42cbbe8b23f31a256f75a366e5a1bcd59b33543',
        '2DFAN4-cd938726ad.zip': 'cd938726adb1f15f361263cce2db9cb820c42585fa8796ec72ce19107f369a46',
    }
    for name, digest in landmark_files.items():
        dest = Path(torch.hub.get_dir()) / 'checkpoints' / name
        if dest.is_file() and hashlib.sha256(dest.read_bytes()).hexdigest() == digest:
            continue
        url = 'https://huggingface.co/chunyu-li/face-alignment/resolve/30a934a95e2f903250ecf929846a1ebc475c2b0f/' + name
        data = urllib.request.urlopen(url, timeout=120).read()
        if hashlib.sha256(data).hexdigest() != digest:
            raise RuntimeError('Landmark model checksum mismatch: ' + name)
        dest.parent.mkdir(exist_ok=True, parents=True)
        temp = dest.with_suffix('.download')
        temp.write_bytes(data)
        temp.replace(dest)
    import face_alignment
    print('Preparing SFD detector and 68-point face-alignment weights on CPU.', flush=True)
    face_alignment.FaceAlignment(face_alignment.LandmarksType.TWO_D, device='cpu', flip_input=False, face_detector='sfd')
    (assets / 'revisions.json').write_text(json.dumps({'FLARE-checkpoints': revision, 'Qwen2.5-7B': qwen_revision, 'FLARE-source': FLARE_REV, 'mean_face_sha256': MEAN_FACE_SHA}, indent=2))
    print('Assets ready. Run the API using .venv-model/bin/python; CUDA memory is checked before model loading.', flush=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--download', action='store_true', help='Download checkpoints, base LLM and face landmark weights (~25 GB).')
    parser.add_argument('--check-load', action='store_true', help='Validate all checkpoint tensors and a model forward pass on CPU; requires ~40 GB RAM.')
    args = parser.parse_args()
    prepare_sources()
    if args.download:
        download_assets()

    if args.check_load:
        import sys
        sys.path.insert(0, str(ROOT))
        import torch
        from backend.model import FlareModel
        torch.set_num_threads(8)
        model = FlareModel()
        model._load_weights(torch, device='cpu')
        print('All visual, Qwen, LoRA and projection tensors loaded successfully on CPU.', flush=True)
        with torch.inference_mode():
            face = torch.zeros((1, 1, 25, 88, 88), dtype=torch.bfloat16)
            mask = torch.zeros((1, 25), dtype=torch.bool)
            result = model.model.encoder(source={'audio': None, 'video': (face, face), 'face_lip_mask': (torch.ones(1), torch.ones(1))}, padding_mask=mask)
            # Exercise the actual released search path (Qwen internals + LoRA head),
            # not the training-oriented top-level forward that expects labels.
            original_beam = model._search.__globals__['beam_search']
            def short_beam(*args, **kwargs):
                kwargs['max_length'] = 4
                return original_beam(*args, **kwargs)
            model._search.__globals__['beam_search'] = short_beam
            sample = {'net_input': {'source': {'audio': None, 'video': (face, face), 'face_lip_mask': (torch.ones(1), torch.ones(1))}, 'padding_mask': mask}}
            hypotheses, _ = model._search([model.model], sample, beam_size=1, audio_only=False, video_only=True, temp=1.2)
            model._search.__globals__['beam_search'] = original_beam
        print(f'CPU forward + bounded beam search passed: visual {tuple(result["encoder_out"].shape)}, {len(hypotheses)} hypothesis. This synthetic check does not measure speech accuracy.', flush=True)
